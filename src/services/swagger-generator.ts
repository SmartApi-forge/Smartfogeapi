/**
 * Join path segments, handling empty base paths
 */
function joinPath(base: string, path: string): string {
  if (!base) return path;
  return `${base.replace(/\/$/, '')}/${path.replace(/^\//, '')}`;
}

/**
 * Get the list of dependencies required for Swagger UI
 * 
 * @returns Object with package names and versions
 */
export function getSwaggerDependencies(): Record<string, string> {
  return { ...SWAGGER_DEPENDENCIES };
}

/**
 * Check if a project has Swagger UI dependencies installed
 * 
 * @param packageJson - The package.json content as an object
 * @returns Whether swagger-ui-react is in dependencies
 */
export function hasSwaggerDependency(
  packageJson: { dependencies?: Record<string, string> }
): boolean {
  return !!packageJson.dependencies?.['swagger-ui-react'];
}

/**
 * Get the package.json additions needed for Swagger UI
 * 
 * @returns Partial package.json object with dependencies
 */
export function getPackageJsonAdditions(): { dependencies: Record<string, string> } {
  return {
    dependencies: { ...SWAGGER_DEPENDENCIES },
  };
}

/**
 * Generate a minimal Swagger UI page (without extra features)
 * 
 * @param specUrl - URL to fetch the OpenAPI spec
 * @returns Minimal page component code
 */
export function generateMinimalSwaggerPage(specUrl: string): string {
  return `'use client';

import dynamic from 'next/dynamic';
import 'swagger-ui-react/swagger-ui.css';

const SwaggerUI = dynamic(() => import('swagger-ui-react'), { ssr: false });

export default function ApiDocsPage() {
  return <SwaggerUI url="${specUrl}" />;
}
`;
}

/**
 * Generate an inline spec route (spec embedded in the route file)
 * Useful for smaller specs that don't need a separate file
 * 
 * @param spec - The OpenAPI spec object
 * @returns Route handler code with embedded spec
 */
export function generateInlineSpecRoute(spec: object): string {
  const specJson = JSON.stringify(spec, null, 2);
  
  return `/**
 * OpenAPI Specification Route (Inline)
 * 
 * Serves the OpenAPI spec embedded directly in this file.
 * Generated by SmartAPIForge
 */

import { NextResponse } from 'next/server';

const openAPISpec = ${specJson};

export async function GET() {
  return NextResponse.json(openAPISpec, {
    headers: {
      'Access-Control-Allow-Origin': '*',
      'Cache-Control': 'public, max-age=3600',
    },
  });
}
`;
}
