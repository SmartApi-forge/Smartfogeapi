/**
 * Generate all Swagger UI files for an API project
 * 
 * This is the main entry point for generating Swagger documentation.
 * It creates all necessary files for a complete Swagger UI integration.
 * 
 * @param options - Generation options
 * @returns All generated files and metadata
 */
export function generateSwaggerFiles(
  options: GenerateSwaggerOptions
): SwaggerGeneratorResult {
  const {
    apiName,
    specContent,
    config = {},
    basePath = '',
    includeLayout = true,
  } = options;

  // Merge with default config
  const fullConfig: SwaggerUIConfig = {
    ...DEFAULT_CONFIG,
    ...config,
    title: config.title || `${apiName} API Documentation`,
  };

  // Generate file paths
  const filePaths: SwaggerFilePaths = {
    docsPage: joinPath(basePath, 'app/api-docs/page.tsx'),
    specRoute: joinPath(basePath, 'app/api/openapi/route.ts'),
    specYaml: joinPath(basePath, 'public/openapi.yaml'),
  };

  if (includeLayout) {
    filePaths.docsLayout = joinPath(basePath, 'app/api-docs/layout.tsx');
  }

  // Generate all files
  const result: SwaggerGeneratorResult = {
    docsPage: generateSwaggerUIPage(fullConfig),
    specRoute: generateOpenAPIRoute(specContent),
    specYaml: specContent,
    dependencies: { ...SWAGGER_DEPENDENCIES },
    filePaths,
  };

  return result;
}

/**
 * Generate a complete set of documentation files including README
 * 
 * @param options - Generation options
 * @returns Object with all file contents keyed by path
 */
export function generateCompleteSwaggerDocs(
  options: GenerateSwaggerOptions
): Record<string, string> {
  const result = generateSwaggerFiles(options);
  const { apiName, basePath = '' } = options;

  const files: Record<string, string> = {
    [result.filePaths.docsPage]: result.docsPage,
    [result.filePaths.specRoute]: result.specRoute,
    [result.filePaths.specYaml]: result.specYaml,
  };

  // Add layout if path exists
  if (result.filePaths.docsLayout) {
    files[result.filePaths.docsLayout] = generateDocsLayout(
      `${apiName} API Documentation`
    );
  }

  // Add README
  const readmePath = joinPath(basePath, 'docs/API_DOCS.md');
  files[readmePath] = generateDocsReadme(apiName, '/api-docs');

  return files;
}

